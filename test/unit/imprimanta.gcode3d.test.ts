import assert from 'node:assert/strict';
import test from 'node:test';
import { analizeazaFisier, analizor, analizeazaText, patPentru, secunde } from '../../src/machine/imprimanta/gcode3d.ts';

/*
 * Verificarea unui `.gcode` înainte de trimitere (ADR 0190 §D, felia 3.6h), pe hârtie: antetele lui OrcaSlicer (și Creality
 * Print, care e OrcaSlicer), PrusaSlicer și Cura; temperaturile din comenzi; miniatura; întinderea mișcărilor cu G90, G91, G92,
 * G28 și arce, pe valori calculate de mână; bucățile (un fișier citit pe bucăți dă aceeași analiză).
 */

const K1C = patPentru('K1C');

const ORCA = [
  '; HEADER_BLOCK_START',
  '; generated by OrcaSlicer 2.3.0 on 2026-11-07 at 10:00:00',
  '; model printing time: 40m 5s; total estimated time: 41m 2s',
  '; HEADER_BLOCK_END',
  '',
  '; THUMBNAIL_BLOCK_START',
  '; thumbnail begin 16x16 30',
  '; iVBORw0KGgoAAAA',
  '; thumbnail end',
  '; thumbnail begin 32x32 40',
  '; iVBORw0KGgoBBBBBBBB',
  '; CCCCCCCC',
  '; thumbnail end',
  '; THUMBNAIL_BLOCK_END',
  'M140 S0',
  'M104 S0',
  'START_PRINT EXTRUDER_TEMP=220 BED_TEMP=55',
  'G90',
  'G1 Z0.2 F600',
  'G1 X10 Y20 E1',
  'G1 X200.5 Y210 E2 ; perimetru',
  'END_PRINT',
  '; CONFIG_BLOCK_START',
  '; filament_type = PLA;PETG',
  '; nozzle_diameter = 0.4,0.4',
  '; nozzle_temperature = 999',
  '; printer_model = Creality K1C',
  '; printer_settings_id = Creality K1C 0.4 nozzle',
  '; CONFIG_BLOCK_END',
].join('\n');

test('antetul lui OrcaSlicer: imprimanta, duza, materialul, timpul total, temperaturile din START_PRINT, miniatura cea mare', () => {
  const a = analizeazaText(ORCA, K1C);
  assert.equal(a.imprimanta, 'Creality K1C');
  assert.equal(a.duza, 0.4);
  assert.equal(a.material, 'PLA');
  // „total estimated time”, nu „model printing time”: 41 × 60 + 2.
  assert.equal(a.timp, 2462);
  // M104 S0 și M140 S0 nu sunt o temperatură; START_PRINT le dă. Configurația (nozzle_temperature) nu e o comandă.
  assert.equal(a.tDuza, 220);
  assert.equal(a.tPat, 55);
  assert.equal(a.miniatura, 'iVBORw0KGgoBBBBBBBBCCCCCCCC');
  assert.equal(a.miscari, 3);
  assert.deepEqual(a.min, [10, 20, 0.2]);
  assert.deepEqual(a.max, [200.5, 210, 0.2]);
  assert.equal(a.iesire, null);
});

test('antetul lui Cura (Creality Print 4) și al lui PrusaSlicer; temperaturile din M109 / M190; o miniatură care nu e PNG se sare', () => {
  const cura = analizeazaText([
    ';FLAVOR:Marlin', ';TIME:2460', ';TARGET_MACHINE.NAME:Creality K1 Max', ';EXTRUDER_TRAIN.0.NOZZLE.DIAMETER:0.6',
    'M190 S60', 'M109 S210', 'G1 X1 Y1',
  ].join('\n'), patPentru('K1 Max'));
  assert.deepEqual(
    [cura.imprimanta, cura.duza, cura.timp, cura.tDuza, cura.tPat, cura.material, cura.miniatura],
    ['Creality K1 Max', 0.6, 2460, 210, 60, null, null],
  );
  const prusa = analizeazaText([
    '; thumbnail_JPG begin 16x16 8', '; /9j/4AAQ', '; thumbnail_JPG end',
    '; thumbnail_QOI begin 16x16 8', '; cW9pZg==', '; thumbnail_QOI end',
    'M104 S0', 'M104 S215', 'M140 S65',
    '; estimated printing time (normal mode) = 1d 2h 3m 4s', '; estimated first layer printing time (normal mode) = 9m',
  ].join('\n'), K1C);
  assert.equal(prusa.timp, 86400 + 2 * 3600 + 3 * 60 + 4);
  assert.equal(prusa.tDuza, 215);
  assert.equal(prusa.tPat, 65);
  assert.equal(prusa.miniatura, null);
  // Un bloc „thumbnail begin” cu altceva decât un PNG (aici un GIF) nu e o miniatură.
  assert.equal(analizeazaText(['; thumbnail begin 1x1 8', '; R0lGODlhAQABAAAAACw=', '; thumbnail end'].join('\n'), K1C).miniatura, null);
  // O miniatură fără sfârșit nu înghite restul antetului: după 20 000 de linii, citirea antetului se reia.
  const fara = analizeazaText(['; thumbnail begin 1x1 8', ...Array.from({ length: 20001 }, () => '; QUFBQUFB'), '; printer_model = Creality K1C'].join('\n'), K1C);
  assert.deepEqual([fara.miniatura, fara.imprimanta], [null, 'Creality K1C']);
  assert.equal(secunde('2460'), 2460);
  assert.equal(secunde('45m 12s'), 2712);
  assert.equal(secunde('nimic'), null);
});

test('patul: K1, K1C și K1 SE au 220 × 220 × 250, K1 Max 300 × 300 × 300; fără model, ca K1C', () => {
  assert.deepEqual(patPentru('K1C'), [220, 220, 250]);
  assert.deepEqual(patPentru('K1 SE'), [220, 220, 250]);
  assert.deepEqual(patPentru(null), [220, 220, 250]);
  assert.deepEqual(patPentru('K1 Max'), [300, 300, 300]);
});

test('întinderea, cu G90, G91 și G92, pe valori de pe hârtie; G1 doar cu E sau F nu e o mișcare', () => {
  const a = analizeazaText([
    'G28', 'G90', 'G1 Z0.3', 'G1 X10 Y20', 'G1 E5 F1800', 'G1 X200 Y210 E5',
    'G91', 'G1 X5 Y-3', 'G90',
    // Scrisul X0 e la 205 reali: deplasarea 205, deci X10 e la 215.
    'G92 X0', 'G1 X10', 'G92 E0',
  ].join('\n'), K1C);
  assert.equal(a.miscari, 5);
  assert.deepEqual(a.min, [10, 20, 0.3]);
  assert.deepEqual(a.max, [215, 210, 0.3]);
  assert.equal(a.iesire, null);
});

test('o mișcare în afara patului: prima, cu linia, textul, axa și valoarea; și sub zero', () => {
  const peste = analizeazaText(['G90', 'G1 X10 Y10', 'G1 X231 Y40 ; prea departe', 'G1 X300'].join('\n'), K1C);
  assert.deepEqual(peste.iesire, { linie: 3, text: 'G1 X231 Y40 ; prea departe', axa: 'X', valoare: 231 });
  assert.equal(peste.max[0], 300);
  const sub = analizeazaText(['G90', 'G1 X10 Y10 Z0.2', 'G91', 'G1 Y-11'].join('\n'), K1C);
  assert.deepEqual(sub.iesire, { linie: 4, text: 'G1 Y-11', axa: 'Y', valoare: -1 });
  const z = analizeazaText(['G90', 'G1 Z251'].join('\n'), K1C);
  assert.equal(z.iesire?.axa, 'Z');
  // Pe margine e în pat.
  assert.equal(analizeazaText('G90\nG1 X0 Y220 Z250', K1C).iesire, null);
  // Același fișier încape pe un K1 Max.
  assert.equal(analizeazaText(['G90', 'G1 X231 Y40'].join('\n'), patPentru('K1 Max')).iesire, null);
});

test('arcele: G2 orar trece pe sus, G3 pe jos, cercul întreg; un arc cu capetele în pat care iese din el', () => {
  // Centrul (110, 100), raza 10, de la (100, 100) la (120, 100).
  const g2 = analizeazaText('G90\nG1 X100 Y100\nG2 X120 Y100 I10 J0', K1C);
  assert.deepEqual([g2.min[1], g2.max[1], g2.min[0], g2.max[0]], [100, 110, 100, 120]);
  const g3 = analizeazaText('G90\nG1 X100 Y100\nG3 X120 Y100 I10 J0', K1C);
  assert.deepEqual([g3.min[1], g3.max[1]], [90, 100]);
  const cerc = analizeazaText('G90\nG1 X100 Y100\nG2 X100 Y100 I10 J0', K1C);
  assert.deepEqual([cerc.min[0], cerc.max[0], cerc.min[1], cerc.max[1]], [100, 120, 90, 110]);
  // Fără capăt scris, arcul se întoarce de unde a plecat: tot un cerc întreg.
  const faraCapat = analizeazaText('G90\nG1 X100 Y100\nG2 I10 J0', K1C);
  assert.deepEqual([faraCapat.min[0], faraCapat.max[0], faraCapat.min[1], faraCapat.max[1], faraCapat.miscari], [100, 120, 90, 110, 2]);
  // De la (215, 100) la (215, 120), centrul (215, 110): trigonometric trece prin (225, 110), orar prin (205, 110).
  const iese = analizeazaText('G90\nG1 X215 Y100\nG3 X215 Y120 I0 J10', K1C);
  assert.deepEqual(iese.iesire, { linie: 3, text: 'G3 X215 Y120 I0 J10', axa: 'X', valoare: 225 });
  assert.equal(analizeazaText('G90\nG1 X215 Y100\nG2 X215 Y120 I0 J10', K1C).iesire, null);
  // Un sfert de cerc, unde sensul contează (otrava G13 a scăpat pe semicercuri, la care ocolul are aceeași mărime în ambele
  // sensuri): centrul (110, 100), de la (120, 100), unghiul 0, la (110, 110), unghiul π/2. G3 ocolește π/2 și n-atinge
  // nicio altă extremă; G2 ocolește 3π/2, prin (110, 90) și (100, 100).
  const sfertG3 = analizeazaText('G90\nG1 X120 Y100\nG3 X110 Y110 I-10 J0', K1C);
  assert.deepEqual([sfertG3.min[0], sfertG3.max[0], sfertG3.min[1], sfertG3.max[1]], [110, 120, 100, 110]);
  const sfertG2 = analizeazaText('G90\nG1 X120 Y100\nG2 X110 Y110 I-10 J0', K1C);
  assert.deepEqual([sfertG2.min[0], sfertG2.max[0], sfertG2.min[1], sfertG2.max[1]], [100, 120, 90, 110]);
});

test('G28 face poziția neștiută (o mișcare relativă după el nu se mai poate pune pe pat); G1X10 fără spații; litere mici; G29 nu e o mișcare', () => {
  const a = analizeazaText(['G90', 'G1 X10 Y10', 'G28 X', 'G91', 'G1 X500 Y5', 'G90', 'G1X12Y30', 'G29 X999'].join('\n'), K1C);
  assert.equal(a.iesire, null);
  assert.deepEqual([a.min[0], a.max[0]], [10, 12]);
  assert.deepEqual([a.min[1], a.max[1]], [10, 30]);
  assert.equal(a.miscari, 3);
  assert.deepEqual(analizeazaText('g90\ng1 x5 y6 ; mic', K1C).max, [5, 6, null]);
  assert.equal(analizeazaText('; nimic aici\nM117 Salut', K1C).miscari, 0);
});

test('pe bucăți tăiate oriunde (și în mijlocul unei linii), analiza e aceeași', () => {
  const intreg = analizeazaText(ORCA, K1C);
  for (const pas of [1, 7, 64]) {
    const a = analizor(K1C);
    for (let i = 0; i < ORCA.length; i += pas) a.adauga(ORCA.slice(i, i + pas));
    assert.deepEqual(a.gata(), intreg, `bucăți de ${pas}`);
  }
});

test('un fișier citit pe bucăți de 1 MiB: o literă de doi octeți tăiată între bucăți rămâne întreagă; semnalul oprește citirea', async () => {
  const cap = '; printer_model = A';
  const inainte = 1048575 - Buffer.byteLength(cap);
  const text = `;${'x'.repeat(inainte - 2)}\n${cap}ș\nG90\nG1 X1 Y1\n`;
  assert.equal(Buffer.byteLength(text.slice(0, text.indexOf('ș'))), 1048575);
  const a = await analizeazaFisier(new Blob([text]), K1C);
  assert.equal(a.imprimanta, 'Aș');
  assert.equal(a.miscari, 1);
  const c = new AbortController();
  c.abort(new Error('oprit'));
  await assert.rejects(analizeazaFisier(new Blob([text]), K1C, c.signal), /oprit/);
});
