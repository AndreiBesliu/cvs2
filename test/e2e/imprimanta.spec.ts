  const miniatura = dialog.locator('img.imprimanta-miniatura');
  await expect(miniatura).toHaveAttribute('src', `data:image/png;base64,${PNG}`);
  await expect.poll(() => miniatura.evaluate((i) => (i as HTMLImageElement).naturalWidth)).toBe(1);
  // `cub.gcode` e deja în imprimantă: nu se înlocuiește, cel nou pleacă drept `cub-2.gcode`.
